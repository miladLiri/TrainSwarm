def verify():
    thesis_path = Path("Thesis.md").resolve()
    with open(thesis_path, "r", encoding="utf-8") as f:
        text = f.read()

    print(f"Verifying {thesis_path.name}...")
    missing = []
    for sec in REQUIRED_SECTIONS:
        if sec not in text:
            missing.append(sec)

    if missing:
        print(f"FAILED! Found {len(missing)} missing sections:")
        for m in missing:
            print(f"  - {m}")
    else:
        print(f"SUCCESS! All {len(REQUIRED_SECTIONS)} required sections are present.")

    # Check key concepts
    checks = {
        "TinyStories-1M": "TinyStories-1M" in text,
        "SafeTensors": "SafeTensors" in text or "safetensors" in text,
        "FedAvg formula": "Delta W" in text or "\\Delta W" in text,
        "Table 1 (Loss/PPL)": "۴.۱۲۰۵" in text and "۳.۶۴۱۸" in text,
        "Table 2 (Bandwidth 74.8%)": "۷۴.۸" in text,
        "Table 3 (Scalability)": "بهره‌وری موازی" in text,
        "Table 4 (FT Matrix)": "FT-01" in text and "FT-12" in text,
        "libp2p / DCUtR": "DCUtR" in text,
        ".NET 10 Coordinator": ".NET 10" in text,
        "Smoke Test Partitioner": "Smoke Test" in text,
    }

    print("\nKey Technical Invariants:")
    for k, v in checks.items():
        status = "PASS" if v else "FAIL"
        print(f"  [{status}] {k}")

    # Check Word count
    words = re.findall(r'\S+', text)
    print(f"\nTotal Word Count: {len(words):,}")
    print(f"Estimated Word Document Pages: {len(words)/320:.1f} to {len(words)/260:.1f} pages")

if __name__ == "__main__":
    verify()
