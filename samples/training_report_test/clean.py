"""
clean.py

Cleans output artifacts generated by train.py and show_report.py.
Retains base artifacts in artifacts/ and fine-tuning-dataset/.
Runs without command-line arguments.
"""

from __future__ import annotations
import os
from pathlib import Path
import shutil
import sys

SCRIPT_DIR = Path(__file__).resolve().parent

PATHS_TO_REMOVE = [
    SCRIPT_DIR / "work",
    SCRIPT_DIR / "training_metrics.json",
    SCRIPT_DIR / "training_metrics.json.tmp",
    SCRIPT_DIR / "training_lifecycle_metrics.json",
    SCRIPT_DIR / "training_metrics_plot.png",
    SCRIPT_DIR / "single_node_finetuning",
    SCRIPT_DIR / "hf_trainer_output",
]


def main() -> None:
    print("=" * 65)
    print(" Cleaning Training Run Outputs ")
    print("=" * 65)
    removed_count = 0

    for path in PATHS_TO_REMOVE:
        if path.is_dir():
            shutil.rmtree(path, ignore_errors=True)
            print(f"[-] Removed directory: '{path.name}/'")
            removed_count += 1
        elif path.is_file():
            try:
                path.unlink()
                print(f"[-] Removed file:      '{path.name}'")
                removed_count += 1
            except OSError as e:
                print(f"[!] Warning deleting '{path.name}': {e}")

    print("=" * 65)
    print(f"[+] Cleanup completed. ({removed_count} item(s) cleaned)\n")


if __name__ == "__main__":
    main()
